def P(text, style="body"):
    return Paragraph(text, S[style])


def cell(text, style="cell"):
    return Paragraph(text, S[style])


def table(rows, widths, header=True, zebra=True, pad=5):
    data = [[cell(c, "cellb" if (header and i == 0) else "cell") for c in row]
            for i, row in enumerate(rows)]
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    cmds = [
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), pad),
        ("BOTTOMPADDING", (0, 0), (-1, -1), pad),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("LINEBELOW", (0, 0), (-1, -2), 0.4, RULE),
        ("LINEBELOW", (0, -1), (-1, -1), 0.8, RULE),
    ]
    if header:
        cmds += [("BACKGROUND", (0, 0), (-1, 0), BAND),
                 ("LINEBELOW", (0, 0), (-1, 0), 0.8, DIM)]
    if zebra:
        for i in range(1 if header else 0, len(data)):
            if i % 2 == (0 if header else 1):
                cmds.append(("BACKGROUND", (0, i), (-1, i), colors.HexColor("#FAFCFD")))
    t.setStyle(TableStyle(cmds))
    return t


def beat(time, where, step, head, operate, say, point, caution=None):
    """시연 한 장면. 시각 · 화면 · 조작 · 대사 · 짚을 곳 · 주의."""
    bits = [Paragraph("%s　|　%s　|　%s" % (time, where, step), S["h2"])]
    bits.append(P(B(head)))
    bits.append(P("<b>조작</b>　" + operate, "note"))
    bits.append(Paragraph("“" + say + "”", S["say"]))
    bits.append(P("<b>짚어 줄 곳</b>　" + point, "note"))
    if caution:
        bits.append(P("<b>주의</b>　" + caution, "warn"))
    bits.append(Spacer(1, 7))
    return KeepTogether(bits)


